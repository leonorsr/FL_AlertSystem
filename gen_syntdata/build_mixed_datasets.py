from __future__ import annotations

import argparse
import json
import math
import shutil
from pathlib import Path

import numpy as np
import pandas as pd


RATIOS = {
    "25_synthetic_75_original": 0.25,
    "50_synthetic_50_original": 0.50,
    "70_synthetic_30_original": 0.70,
    "90_synthetic_10_original": 0.90,
}


METADATA_COLUMNS = {
    "dataset",
    "client",
    "trial_id",
    "label",
    "variant",
    "feature_set",
    "window_start_sec",
    "window_end_sec",
    "window_seconds",
    "timestep",
    "source",
}


def feature_columns_from_synthetic(synthetic_df: pd.DataFrame) -> list[str]:
    return [column for column in synthetic_df.columns if column not in METADATA_COLUMNS]


def required_synthetic_rows(original_rows: int, synthetic_ratio: float) -> int:
    if not 0.0 < synthetic_ratio < 1.0:
        raise ValueError("Synthetic ratio must be between 0 and 1.")
    raw_count = (synthetic_ratio * original_rows) / (1.0 - synthetic_ratio)
    nearest_integer = round(raw_count)
    if math.isclose(raw_count, nearest_integer, rel_tol=1e-12, abs_tol=1e-9):
        return int(nearest_integer)
    return int(math.ceil(raw_count))


def normalize_original(original_df: pd.DataFrame, feature_columns: list[str]) -> pd.DataFrame:
    missing = [column for column in feature_columns if column not in original_df.columns]
    if missing:
        raise ValueError(f"Original CSV is missing feature columns generated by TimeGAN: {missing}")

    original = original_df.copy()
    original["source"] = "original"
    return original


def normalize_synthetic(
    synthetic_df: pd.DataFrame,
    original_columns: list[str],
    feature_columns: list[str],
    synthetic_dataset: str,
    synthetic_client: str,
    window_seconds: float,
) -> pd.DataFrame:
    synthetic = synthetic_df.copy()
    synthetic["dataset"] = synthetic_dataset
    synthetic["client"] = synthetic_client
    synthetic["label"] = 1
    synthetic["source"] = "synthetic"

    if "window_start_sec" in original_columns:
        synthetic["window_start_sec"] = synthetic["timestep"].astype(float) * window_seconds
    if "window_end_sec" in original_columns:
        synthetic["window_end_sec"] = synthetic["window_start_sec"] + window_seconds
    if "window_seconds" in original_columns:
        synthetic["window_seconds"] = window_seconds
    if "variant" in original_columns:
        synthetic["variant"] = "timegan_sequence_ready_nn"
    if "feature_set" in original_columns:
        synthetic["feature_set"] = ",".join(feature_columns)

    for column in original_columns:
        if column not in synthetic.columns:
            synthetic[column] = np.nan

    return synthetic[original_columns + ["source"]]


def ensure_synthetic_capacity(
    synthetic_path: Path,
    required_rows: int,
    run_dir: Path,
    device: str,
) -> None:
    if synthetic_path.exists():
        current_rows = sum(1 for _ in synthetic_path.open("r", encoding="utf-8")) - 1
        if current_rows >= required_rows:
            return

    seq_len = 32
    required_sequences = int(math.ceil(required_rows / seq_len))
    import subprocess

    subprocess.run(
        [
            "venv/bin/python",
            "-m",
            "gen_syntdata.generate_timegan",
            "--run-dir",
            str(run_dir),
            "--count",
            str(required_sequences),
            "--output",
            str(synthetic_path),
            "--device",
            device,
        ],
        check=True,
    )


def write_dataset(
    folder: Path,
    original: pd.DataFrame,
    synthetic: pd.DataFrame,
    synthetic_ratio: float,
) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    target_synthetic_rows = required_synthetic_rows(len(original), synthetic_ratio)
    synthetic_sample = synthetic.head(target_synthetic_rows).copy()
    mixed = pd.concat([original, synthetic_sample], ignore_index=True)

    original.to_csv(folder / "original_windows.csv", index=False)
    synthetic_sample.to_csv(folder / "synthetic_windows.csv", index=False)
    mixed.to_csv(folder / "mixed_windows.csv", index=False)

    summary = {
        "original_rows": int(len(original)),
        "synthetic_rows": int(len(synthetic_sample)),
        "total_rows": int(len(mixed)),
        "original_trials": int(original["trial_id"].nunique()),
        "synthetic_trials": int(synthetic_sample["trial_id"].nunique()),
        "target_synthetic_ratio": float(synthetic_ratio),
        "actual_synthetic_ratio_by_rows": float(len(synthetic_sample) / len(mixed)),
        "actual_original_ratio_by_rows": float(len(original) / len(mixed)),
        "original_labels_by_rows": {str(k): int(v) for k, v in original["label"].value_counts().sort_index().items()},
        "synthetic_labels_by_rows": {str(k): int(v) for k, v in synthetic_sample["label"].value_counts().sort_index().items()},
    }
    (folder / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build mixed datasets with all original rows fixed and variable TimeGAN synthetic rows."
    )
    parser.add_argument(
        "--original",
        default="fl/data/preprocessing_results/composed/sequence_ready_nn/windows.csv",
        type=Path,
    )
    parser.add_argument(
        "--synthetic",
        default="gen_syntdata/runs/falls_timegan/synthetic_falls_for_mixtures.csv",
        type=Path,
    )
    parser.add_argument("--timegan-run-dir", default="gen_syntdata/runs/falls_timegan", type=Path)
    parser.add_argument("--output-dir", default="gen_syntdata/mixed_datasets", type=Path)
    parser.add_argument("--synthetic-dataset", default="KFall")
    parser.add_argument("--synthetic-client", default="SA06")
    parser.add_argument("--device", default="cpu")
    parser.add_argument("--force", action="store_true", help="Remove the output directory before rebuilding.")
    args = parser.parse_args()

    original_df = pd.read_csv(args.original).dropna(axis=1, how="all")
    existing_synthetic_df = pd.read_csv(args.synthetic) if args.synthetic.exists() else pd.read_csv(
        args.timegan_run_dir / "synthetic_falls_900.csv"
    )
    feature_columns = feature_columns_from_synthetic(existing_synthetic_df)

    original = normalize_original(original_df, feature_columns)
    max_required_rows = max(required_synthetic_rows(len(original), ratio) for ratio in RATIOS.values())
    ensure_synthetic_capacity(
        synthetic_path=args.synthetic,
        required_rows=max_required_rows,
        run_dir=args.timegan_run_dir,
        device=args.device,
    )

    synthetic_df = pd.read_csv(args.synthetic)
    window_seconds = float(original["window_seconds"].mode().iloc[0]) if "window_seconds" in original.columns else 1.0
    synthetic = normalize_synthetic(
        synthetic_df=synthetic_df,
        original_columns=original_df.columns.tolist(),
        feature_columns=feature_columns,
        synthetic_dataset=args.synthetic_dataset,
        synthetic_client=args.synthetic_client,
        window_seconds=window_seconds,
    )

    if args.force and args.output_dir.exists():
        shutil.rmtree(args.output_dir)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    for folder_name, synthetic_ratio in RATIOS.items():
        write_dataset(
            folder=args.output_dir / folder_name,
            original=original,
            synthetic=synthetic,
            synthetic_ratio=synthetic_ratio,
        )

    manifest = {
        "source_original": str(args.original),
        "source_synthetic": str(args.synthetic),
        "output_dir": str(args.output_dir),
        "ratios": RATIOS,
        "original_rows_fixed": int(len(original)),
        "original_trials_fixed": int(original["trial_id"].nunique()),
        "synthetic_dataset": args.synthetic_dataset,
        "synthetic_client": args.synthetic_client,
        "feature_columns": feature_columns,
    }
    (args.output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Mixed datasets exported to: {args.output_dir}")


if __name__ == "__main__":
    main()
